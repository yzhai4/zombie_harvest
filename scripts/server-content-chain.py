"""Browser regression for registered-chain UI, using explicit boot-save scenarios.

This tests the real HTML, loader, DOM controls, reducers and saved output. It
does not claim a natural four-day playthrough. Fixtures are built from a fresh
save generated by public controls, then seeded before reloading the document.
No hidden runtime state is changed after boot.
"""

from __future__ import annotations

import copy
import datetime as dt
import hashlib
import json
import os
from pathlib import Path

from playwright.sync_api import sync_playwright


BASE_URL = os.environ.get("ZFARM_TEST_URL", "http://127.0.0.1/")
OUT = Path(os.environ.get("ZFARM_TEST_OUT", "/home/ubuntu/zfarm-qa/content-chain-result.json"))
SAVE_KEY = "zombie-harvest-progress-v12"
CHAIN = "watermill-002"


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    result = {"runner": "server-content-chain", "url": BASE_URL,
              "mode": "explicit-boot-save-fixtures", "startedAt": dt.datetime.now(dt.timezone.utc).isoformat(),
              "checks": [], "errors": [], "httpErrors": [], "consoleErrors": [], "scenarios": {}}

    def check(name: str, condition: bool) -> None:
        result["checks"].append({"name": name, "ok": bool(condition)})
        if not condition:
            result["errors"].append(f"check:{name}")

    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True, executable_path=os.environ.get("CHROME_BIN", "/usr/bin/google-chrome"),
                                    args=["--no-sandbox", "--disable-dev-shm-usage"])
        context = browser.new_context(viewport={"width": 1440, "height": 900})
        page = context.new_page()
        # Seed after the previous document's pagehide checkpoint, before the
        # game's loader. Injecting localStorage in a running game is otherwise
        # overwritten on reload by that legitimate checkpoint.
        page.add_init_script("""{
            const fixture = sessionStorage.getItem('zfarm-qa-boot-fixture');
            if (fixture) {
                localStorage.clear(); sessionStorage.removeItem('zfarm-qa-boot-fixture');
                localStorage.setItem('zombie-harvest-progress-v12', fixture);
            }
        }""")
        # Test-only registered definition exercises choice 3 without shipping
        # new gameplay. It uses the public registry and is present before start.
        page.add_init_script("""window.addEventListener('DOMContentLoaded', () => {
            window.ZombieHarvestContent.register('eventChain', {
                chainId:'qa-three-choices', title:'多路线测试', phase:['day_4','day_10'],
                nodes:[{nodeId:'decision', choices:[1,2,3].map(n => ({id:'route-'+n, label:'测试路线 '+n, effects:[{op:'addResource',key:'parts',value:n}]}))}],
                fallback:{ifMissingNpc:'ledger_only',ifInsufficientPopulation:'ledger_only',ifExpired:'ledger_only',ifSkipped:'ledger_only'}
            });
        });""")
        page.on("pageerror", lambda exc: result["errors"].append(f"pageerror:{exc}"))
        page.on("console", lambda msg: result["consoleErrors"].append(msg.text) if msg.type == "error" else None)
        page.on("response", lambda response: result["httpErrors"].append(f"{response.status}:{response.url}")
                if response.status >= 400 and not response.url.endswith("/favicon.ico") else None)

        def saved() -> dict:
            return page.evaluate("key => JSON.parse(localStorage.getItem(key) || 'null')?.payload", SAVE_KEY) or {}

        def seed(base: dict, parts: int = 20, day: int = 4, dead: bool = False, broken: bool = False) -> dict:
            payload = copy.deepcopy(base)
            payload.update({"day": day, "hour": 8, "minute": 0, "parts": parts, "night": False,
                            "nightBattle": None, "worldZombies": []})
            payload["worldMeta"]["clock"]["paused"] = True
            payload["worldMeta"]["events"] = []
            payload["worldMeta"]["eventSeq"] = 0
            payload["worldMeta"]["commandSeq"] = 0
            payload["worldMeta"]["seenCommands"] = []
            payload["worldMeta"]["replay"]["commands"] = []
            cs = payload["contentState"]
            cs["meters"].update({"campTrust": 25, "campCollapse": 10, "resonancePressure": 25})
            cs["activeChains"] = {CHAIN: {"chainId": CHAIN, "nodeId": "repair_gate", "status": "active", "startedAt": 480, "actorId": "player-1"}}
            cs["completedChains"] = []
            cs["appliedEffects"] = []
            cs["flags"] = {}
            if broken:
                cs["activeChains"]["aaa-broken"] = None
                cs["activeChains"]["aaa-missing-pack"] = {"chainId": "aaa-missing-pack", "nodeId": "absent", "status": "active"}
                cs["activeChains"]["aaa-wrong-key"] = {"chainId": CHAIN, "nodeId": "repair_gate", "status": "active"}
            for npc in payload["npcs"]:
                if dead and npc["id"] == "carpenter":
                    npc.update({"hp": 0, "lifeState": "dead", "behaviorState": "dead"})
            for landmark in payload["landmarks"]:
                if landmark["type"] == "waterMill":
                    landmark["found"] = True
            payload["event"].update({"handled": False, "result": ""})
            payload["eventInstance"].update({"handled": False, "status": "active"})
            return payload

        def load_fixture(payload: dict, width: int = 1440) -> None:
            page.set_viewport_size({"width": width, "height": 900 if width > 560 else 844})
            # Compute the runtime's FNV checksum using JS JSON serialization,
            # including UTF-16 iteration, before passing through the real loader.
            page.evaluate("""({key, payload}) => {
                localStorage.clear(); sessionStorage.clear();
                const text = JSON.stringify(payload); let h = 2166136261;
                for (let i=0; i<text.length; i++) { h ^= text.charCodeAt(i); h = Math.imul(h,16777619); }
                sessionStorage.setItem('zfarm-qa-boot-fixture', JSON.stringify({version:21, payload, checksum:(h>>>0).toString(16), reason:'qa-explicit-fixture'}));
            }""", {"key": SAVE_KEY, "payload": payload})
            page.reload(wait_until="domcontentloaded", timeout=30000)
            page.locator("#continueSaveBtn").click()
            page.locator("#eventToggle").click()
            page.locator("#eventPanel").wait_for(state="visible")

        def choose_chain() -> None:
            page.locator("#eventSourceSelect").select_option(f"chain:{CHAIN}")

        def checkpoint() -> dict:
            page.wait_for_function("key => JSON.parse(localStorage.getItem(key) || 'null')?.payload?.worldMeta?.events?.some(e => e.type === 'content.chain.command')", arg=SAVE_KEY, timeout=5000)
            return saved()

        try:
            response = page.goto(BASE_URL, wait_until="domcontentloaded", timeout=30000)
            check("page loads", response is not None and response.status == 200)
            result["htmlSha256"] = hashlib.sha256(response.body()).hexdigest()
            page.evaluate("localStorage.clear(); sessionStorage.clear();")
            page.reload(wait_until="domcontentloaded", timeout=30000)
            page.locator("#continueSaveBtn").click()
            page.locator("#gatherBtn").click()
            page.wait_for_function("key => !!localStorage.getItem(key)", arg=SAVE_KEY, timeout=5000)
            base = saved()
            check("fresh save generated by controls", base.get("version") == 21 and len(base.get("npcs", [])) == 10)

            load_fixture(seed(base, broken=True))
            check("pending daily event remains default", page.locator("#eventSourceSelect").input_value() == "daily")
            check("missing and corrupt chains do not block valid chain", page.locator(f'#eventSourceSelect option[value="chain:{CHAIN}"]').count() == 1)
            choose_chain()
            check("friendly title and costs shown", page.locator("#eventTitle").inner_text() == "水车闸门" and "20" in page.locator("#eventChoiceA").inner_text())
            check("both watermill routes available", page.locator("#eventChoiceA").is_enabled() and page.locator("#eventChoiceB").is_enabled())
            page.screenshot(path=str(OUT.parent / "content-chain-desktop.png"))
            # Second synthetic click occurs synchronously, as a fast double tap.
            page.locator("#eventChoiceA").evaluate("button => { button.click(); button.click(); }")
            repair = checkpoint()
            cs = repair["contentState"]
            check("repair cost and collapse applied once", repair["parts"] == 0 and cs["meters"]["campCollapse"] == 6)
            check("repair flag and terminal state saved", cs["flags"].get("watermill_t2") is True and CHAIN in cs["completedChains"] and CHAIN not in cs["activeChains"])
            check("double click does not resolve daily event", repair["event"]["handled"] is False)
            check("result receipt prevents cross-event click", page.locator("#eventChoiceA").is_disabled() and "零件 -20" in page.locator("#eventText").inner_text())
            events = repair["worldMeta"]["events"]
            check("one successful chain command in ledger", sum(e["type"] == "content.chain.command" for e in events) == 1 and sum(e["type"] == "content.chain.resolved" for e in events) == 1)
            result["scenarios"]["repair"] = {"parts": repair["parts"], "collapse": cs["meters"]["campCollapse"], "eventTypes": [e["type"] for e in events]}
            page.reload(wait_until="domcontentloaded")
            page.locator("#continueSaveBtn").click()
            page.locator("#eventToggle").click()
            check("completed chain cannot be selected after reload", page.locator(f'#eventSourceSelect option[value="chain:{CHAIN}"]').count() == 0)
            check("repair does not reward again after reload", saved()["parts"] == 0 and CHAIN in saved()["contentState"]["completedChains"])

            load_fixture(seed(base), width=390)
            choose_chain()
            check("mobile selector and choices fit", page.locator("#eventSourceSelect").is_visible() and page.locator("#eventChoiceB").is_visible()
                  and page.evaluate("document.documentElement.scrollWidth <= window.innerWidth"))
            page.screenshot(path=str(OUT.parent / "content-chain-mobile.png"))
            page.locator("#eventChoiceB").click()
            salvage = checkpoint()
            check("salvage resources and pressure saved", salvage["parts"] == 23 and salvage["contentState"]["meters"]["resonancePressure"] == 28)
            check("salvage does not mark repair", not salvage["contentState"]["flags"].get("watermill_t2"))
            page.locator("#eventSourceSelect").select_option("daily")
            check("daily event accessible after side chain", page.locator("#eventChoiceB").is_enabled() and page.locator("#eventChoiceB").get_attribute("data-event-source") == "daily")
            result["scenarios"]["salvage"] = {"parts": salvage["parts"], "resonance": salvage["contentState"]["meters"]["resonancePressure"]}

            load_fixture(seed(base, parts=19))
            choose_chain()
            check("insufficient materials lock repair only", page.locator("#eventChoiceA").is_disabled() and page.locator("#eventChoiceB").is_enabled())
            load_fixture(seed(base, dead=True))
            choose_chain()
            check("dead carpenter locks repair only", page.locator("#eventChoiceA").is_disabled() and page.locator("#eventChoiceB").is_enabled())
            load_fixture(seed(base, day=11))
            choose_chain()
            check("expired save cannot claim either route", page.locator("#eventChoiceA").is_disabled() and page.locator("#eventChoiceB").is_disabled())
            check("expired route shows reason", "错过" in page.locator("#eventChoiceA").inner_text())

            three_choices = seed(base)
            three_choices["contentState"]["activeChains"] = {"qa-three-choices": {"chainId": "qa-three-choices", "nodeId": "decision", "status": "active"}}
            load_fixture(three_choices, width=390)
            page.locator("#eventSourceSelect").select_option("chain:qa-three-choices")
            third = page.locator('[data-chain-choice-index="2"]')
            check("third registered choice is visible and enabled", third.is_visible() and third.is_enabled())
            third.click()
            third_result = checkpoint()
            check("third choice executes the registered route", third_result["parts"] == 23 and any(e["type"] == "content.chain.resolved" and e["payload"]["choiceId"] == "route-3" for e in third_result["worldMeta"]["events"]))
            check("third choice preserves daily event", third_result["event"]["handled"] is False)
        except Exception as exc:
            result["errors"].append(f"aborted:{exc}")
        finally:
            browser.close()

    result["finishedAt"] = dt.datetime.now(dt.timezone.utc).isoformat()
    result["ok"] = not result["errors"] and not result["httpErrors"] and not [e for e in result["consoleErrors"] if "404" not in e]
    OUT.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, ensure_ascii=False))
    raise SystemExit(0 if result["ok"] else 1)


if __name__ == "__main__":
    main()
